"""gen_em089_actions.py : module/em089_actions.inc = fallback table (category, number) -> motion for every MH4U
em089 action, from dump/em089/actions.txt (tools/em089_actions.py) and the LMT motion list (dump/em089/motions.txt).

The fallback plays the action's main motion once and ends the action, so every (cat, num) the AI requests does
something and returns control to the AI. Hand-ported handlers in module/em089_act.c take precedence.
Main motion = first listed motion that exists in the LMTs and is not an idle loop (2 / 60), else the first valid one.

  gen_em089_actions.py      (writes module/em089_actions.inc)
"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ACT = os.path.join(ROOT, 'dump', 'em089', 'actions.txt')
MOT = os.path.join(ROOT, 'dump', 'em089', 'motions.txt')
OUT = os.path.join(ROOT, 'module', 'em089_actions.inc')
IDLE = {2, 60}


def main():
    valid = set(map(int, open(MOT).read().split()))
    rows = []
    for line in open(ACT).read().splitlines()[1:]:
        p = line.split()
        if len(p) < 4 or not p[0].isdigit() or '-> base' in line: continue
        cat, num = int(p[0]), int(p[1])
        if cat in (10, 11): continue                     # engine reactions: GU numbering, handled separately
        mots = [int(x) for x in re.findall(r'\b\d+\b', line.split(None, 5)[5] if len(p) > 5 else '')
                if int(x) in valid]
        if not mots: continue
        main = next((m for m in mots if m not in IDLE), mots[0])
        rows.append((cat, num, main, p[3]))
    rows.sort()
    with open(OUT, 'w') as f:
        f.write('/* generated by tools/gen_em089_actions.py from dump/em089/actions.txt: MH4U em089 action (category,\n'
                ' * number) -> main motion (bank << 8 | index) and the 4U handler it comes from. Do not edit. */\n')
        f.write('static const struct { uint8_t cat, num; uint16_t motion; } em089_fallback[] = {\n')
        for cat, num, m, h in rows:
            f.write('    {%2d, %3d, 0x%03x},   /* 4U handler 0x%s */\n' % (cat, num, m, h))
        f.write('};\n')
    print(len(rows), 'actions ->', OUT)


if __name__ == '__main__':
    main()
