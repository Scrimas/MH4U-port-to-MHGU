"""em089_slot75_gen.py : generate module/em089_slot75.inc = literal C translation of the 4U em089 slot-75 motion
dispatch and per-motion cases (0x8c3cb0 .. 0x8c5058, v1.1), for module/em089_efx.c em089_slot75().

  python3 tools/em089_slot75_gen.py        (writes module/em089_slot75.inc)

Every instruction of the range becomes one C statement on register-named variables (r0..r10, s0..s31, the flag
pair cmpa/cmpb, fa/fb for float compares); branches become gotos (0x8c5058 -> `end`). Mapped calls / fields:
  0x90f994 curMotion -> curMotion(self) (game.h), 0x91ab1c motionCheck(this, kind, r2 = 0, s0, s1) -> motionCheck,
  [W] fields W+240/244 (curve times) -> st->t1/t2, W+256/260 (curve end times) -> st->e1/e2,
  W+0xf8/0xfc (curve table pointers, 4U .rodata 0xff6ea0 / 0xff769c..0xff78bc) -> st->c1/c2 = s75_curve(4U addr),
  4U this+644 (model layer 0 +68) -> GU this+0x4f4 (layer 0 at 0x4b0, same +80 frame / +108 layout, aim agent).
"""
import os, re, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import a4u, dis4u

LO, HI, END = 0x8c3cb0, 0x8c5058, 0x8c5058
OUT = os.path.join(os.path.dirname(HERE), 'module', 'em089_slot75.inc')
FIELD = {240: 't1', 244: 't2', 256: 'e1', 260: 'e2', 0xf8: 'c1', 0xfc: 'c2'}
BR = re.compile(r'^b(eq|ne|ge|gt|le|lt|hs|lo)?$')
PCREL = re.compile(r'\[pc, #(-?0x[0-9a-f]+|-?\d+)\]')


def flt(v):
    return repr(struct.unpack('<f', struct.pack('<I', v))[0]) + 'f'


def main():
    pools, targets = set(), set()
    for a in range(LO, HI, 4):
        m, o = dis4u.INS(a)
        mm = PCREL.search(o)
        if mm: pools.add(a + 8 + int(mm.group(1), 0))
    for a in range(LO, HI, 4):
        m, o = dis4u.INS(a)
        if a not in pools and BR.match(m):
            targets.add(int(o.split()[0], 16))
    out, skip, fcmp = [], False, False
    for a in range(LO, HI, 4):
        if a in targets:
            out.append('L%x:' % a); skip = False
        m, o = dis4u.INS(a)
        if a in pools or skip:
            continue
        ops = [x.strip() for x in o.split(',')]
        mm = PCREL.search(o)
        s = None
        if m in ('nop', 'vmrs', 'push', 'vpush'): pass
        elif m == 'bl' and o.startswith('0x90f994'): s = 'r0 = curMotion(self);'
        elif m == 'bl' and o.startswith('0x91ab1c'): s = 'r0 = (uint32_t)motionCheck(self, r1, 0, s0, s1);'
        elif m == 'ldr' and mm: s = '%s = 0x%xu;' % (ops[0], a4u.u(a + 8 + int(mm.group(1), 0)))
        elif m == 'vldr' and mm: s = '%s = %s;' % (ops[0], flt(a4u.u(a + 8 + int(mm.group(1), 0))))
        elif m == 'vldr' and ops[1:] == ['[r5', '#644]']:
            s = '%s = FIELD(float, self, 0x4f4);   /* 4U this+644 */' % ops[0]
        elif m == 'ldr' and ops[1] == '[r4]': s = '%s = 1u;   /* W */' % ops[0]
        elif m == 'vmov.f32': s = '%s = %s;' % (ops[0], ops[1])
        elif m == 'mov' and ops[1].startswith('#'): s = '%s = %du;' % (ops[0], int(ops[1][1:], 0))
        elif m == 'mov': s = '%s = %s;' % (ops[0], '1u' if ops[1] == 'r5' else ops[1])
        elif m in ('add', 'sub', 'subs'):
            b = ops[2]
            bv = '%du' % int(b[1:], 0) if b.startswith('#') else b
            s = '%s = %s %s %s;' % (ops[0], ops[1], '+' if m == 'add' else '-', bv)
            if m == 'subs': s += ' cmpa = (int32_t)%s; cmpb = 0;' % ops[0]
        elif m == 'cmp':
            b = ops[1]
            s = 'cmpa = (int32_t)%s; cmpb = %s;' % (ops[0], ('%d' % int(b[1:], 0)) if b.startswith('#') else '(int32_t)' + b)
        elif m == 'vcmpe.f32':
            s = 'fa = %s; fb = %s;' % (ops[0], ops[1]); fcmp = True
        elif m == 'vstr':
            s = 'st->%s = %s;' % (FIELD[int(re.search(r'#(\d+)\]', o).group(1))], ops[0])
        elif m == 'str':
            s = 'st->%s = s75_curve(%s);' % (FIELD[int(re.search(r'#(0x[0-9a-f]+|\d+)\]', o).group(1), 0)], ops[0])
        elif BR.match(m):
            t = int(o.split()[0], 16)
            cond = {'b': None, 'beq': '==', 'bne': '!=', 'bge': '>=', 'bgt': '>', 'ble': '<=', 'blt': '<'}[m]
            tgt = 'goto end;' if t == END else 'goto L%x;' % t
            if cond is None:
                s = tgt; skip = True
            elif fcmp:
                s = 'if (fa %s fb) %s' % (cond, tgt); fcmp = False
            else:
                s = 'if (cmpa %s cmpb) %s' % (cond, tgt)
        else:
            raise SystemExit('unhandled %x: %s %s' % (a, m, o))
        if s: out.append('    ' + s)
    hdr = ['/* em089_slot75.inc: GENERATED by tools/em089_slot75_gen.py from 4U v1.1 0x8c3cb0..0x8c5058 -- do not edit.',
           ' * Included inside em089_slot75() (module/em089_efx.c). */']
    open(OUT, 'w').write('\n'.join(hdr + out) + '\n')
    print('wrote %s (%d lines)' % (OUT, len(out)))


if __name__ == '__main__':
    main()
