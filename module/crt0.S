@ Module header for MHGU's rtld. rtld reads [base+4] = offset of MOD0, then the MOD0
@ fields relative to MOD0. Hook trampolines are generated by build.py into hooks.inc.

    .include "layout.inc"               @ MAIN_GAP (build.py): main's base = this module's base - MAIN_GAP

    .section .text.crt0, "ax"
    .arm
    .global _start
    .global __module_start
    .hidden __module_start
_start:
__module_start:
    b       1f
    .word   __mod0 - _start
1:  bx      lr

    .align 2
__mod0:
    .ascii  "MOD0"
    .word   _DYNAMIC - __mod0
    .word   __bss_start - __mod0
    .word   __bss_end - __mod0
    .word   0                           @ eh_frame_hdr start (none)
    .word   0                           @ eh_frame_hdr end
    .word   __module_object - __mod0

@ main's runtime base (game.h MAIN): an R_ARM_RELATIVE word, so rtld writes it before anything here runs,
@ wherever the emulator or console loaded the modules.
    .section .data.mainbase, "aw"
    .global g_main_base
    .hidden g_main_base
    .align 2
g_main_base:
    .word   __module_start - MAIN_GAP

    .text
    .include "hooks.inc"
